    // All functions beyond this line were generated by OpenCode Big Pickle
    private async Task LoadAsync(bool reuseExistingDocument = false)
    {
        int generation = Interlocked.Increment(ref _loadGeneration);

        await Dispatcher.UIThread.InvokeAsync(() =>
        {
            IsLoading = true;
            LoadedPageCount = 0;
        });

        try
        {
            if (reuseExistingDocument && Document is not null)
            {
                PdfDocumentModel existingDocument = Document;
                IReadOnlyDictionary<int, FormFieldDescriptor[]> existingFields =
                    GroupFormFieldsByPage(BuildFormFieldDescriptors(existingDocument));

                await Dispatcher.UIThread.InvokeAsync(() =>
                {
                    if (generation != Volatile.Read(ref _loadGeneration)) return;

                    PageElements.Clear();
                    FormFields.Clear();
                    TotalPageCount = existingDocument.Pages.Length;
                });

                await PopulatePageElementsBatchedAsync(existingDocument, existingFields, generation);
                return;
            }

            byte[] documentData = _fileSystemService.ReadPdfData(FilePath);
            string documentName = Path.GetFileName(FilePath);

            // Generated by OpenCode's Big Pickle: pages are streamed from the renderer to the UI
            // instead of waiting for every background image before showing anything.
            var pageQueue = Channel.CreateUnbounded<PdfPageModel>(
                new UnboundedChannelOptions { SingleReader = true, SingleWriter = true });
            var documentReady = new TaskCompletionSource(
                TaskCreationOptions.RunContinuationsAsynchronously);

            IReadOnlyDictionary<int, FormFieldDescriptor[]>? fieldsByPage = null;

            Task renderTask = Task.Run(() =>
            {
                try
                {
                    _pdfService.ConstructPdfDocumentModel(
                        documentData,
                        documentName,
                        _backgroundImageType,
                        onDocumentReady: document =>
                        {
                            // Field descriptors come from the extracted model, before render mutations.
                            fieldsByPage = GroupFormFieldsByPage(BuildFormFieldDescriptors(document));

                            Dispatcher.UIThread.InvokeAsync(() =>
                            {
                                if (generation == Volatile.Read(ref _loadGeneration))
                                {
                                    Document = document;
                                    PageElements.Clear();
                                    FormFields.Clear();
                                    TotalPageCount = document.Pages.Length;
                                }

                                // Release the consumer even when a newer load superseded this one.
                                documentReady.TrySetResult();
                            });
                        },
                        onPageReady: page => pageQueue.Writer.TryWrite(page));
                }
                finally
                {
                    pageQueue.Writer.TryComplete();
                }
            });

            // Wait until the document model has been published before adding any page controls.
            Task finished = await Task.WhenAny(documentReady.Task, renderTask);
            if (finished == renderTask)
                await renderTask;

            await documentReady.Task;

            bool isCurrent = generation == Volatile.Read(ref _loadGeneration);
            if (isCurrent)
            {
                IReadOnlyDictionary<int, FormFieldDescriptor[]> readyFields =
                    fieldsByPage ?? new Dictionary<int, FormFieldDescriptor[]>();

                await foreach (PdfPageModel page in pageQueue.Reader.ReadAllAsync())
                {
                    if (generation != Volatile.Read(ref _loadGeneration)) break;

                    await Dispatcher.UIThread.InvokeAsync(() =>
                    {
                        if (generation != Volatile.Read(ref _loadGeneration)) return;

                        PageElements.Add(CreatePageCanvas(page, readyFields));
                        LoadedPageCount = Math.Max(LoadedPageCount, page.PageNumber);
                    }, DispatcherPriority.Background);

                    // Give Avalonia a chance to lay out/render this page before the next one.
                    await Task.Delay(1);
                }
            }

            await renderTask;
        }
        finally
        {
            await Dispatcher.UIThread.InvokeAsync(() =>
            {
                // Only the current load owns the loading state.
                if (generation == Volatile.Read(ref _loadGeneration))
                    IsLoading = false;
            });
        }
    }

    private static FormFieldDescriptor[] BuildFormFieldDescriptors(PdfDocumentModel document)
    {
        List<FormFieldDescriptor> descriptors = [];

        foreach (PdfPageModel page in document.Pages)
        {
            if (page.FormFieldElements is null) continue;

            foreach (PdfFormFieldElementModel field in page.FormFieldElements)
            {
                Rect bounds = GetDisplayBounds(page, field.Bounds, PointsToDips);
                if (bounds.Width <= 0 || bounds.Height <= 0) continue;

                descriptors.Add(new FormFieldDescriptor(field, bounds, page.PageNumber, field.WidgetKey));
            }
        }

        return [.. descriptors];
    }

    private static IReadOnlyDictionary<int, FormFieldDescriptor[]> GroupFormFieldsByPage(
        FormFieldDescriptor[] formFields) =>
        formFields
            .GroupBy(field => field.PageNumber)
            .ToDictionary(group => group.Key, group => group.ToArray());

    public void PopulatePageElements()
    {
        // Rebuild from the already-loaded model; falls back to reading the file
        // when no model exists yet.
        _ = LoadAsync(reuseExistingDocument: true);
    }

    private async Task PopulatePageElementsBatchedAsync(
        PdfDocumentModel document,
        IReadOnlyDictionary<int, FormFieldDescriptor[]> fieldsByPage,
        int generation)
    {
        for (int start = 0; start < document.Pages.Length; start += PagesPerUiBatch)
        {
            if (generation != Volatile.Read(ref _loadGeneration)) return;

            int batchEnd = Math.Min(start + PagesPerUiBatch, document.Pages.Length);

            await Dispatcher.UIThread.InvokeAsync(() =>
            {
                if (generation != Volatile.Read(ref _loadGeneration)) return;

                for (int i = start; i < batchEnd; i++)
                    PageElements.Add(CreatePageCanvas(document.Pages[i], fieldsByPage));

                LoadedPageCount = batchEnd;
            }, DispatcherPriority.Background);

            // Give Avalonia a chance to lay out/render the new pages and process input
            // before the next batch is created.
            await Task.Delay(1);
        }
    }

    private Canvas CreatePageCanvas(
        PdfPageModel page,
        IReadOnlyDictionary<int, FormFieldDescriptor[]> fieldsByPage)
    {
        var pageSize = GetDisplaySize(page, PointsToDips);

        var pageCanvas = new Canvas
        {
            Width = pageSize.Width,
            Height = pageSize.Height,
            Background = Brushes.White,
            ClipToBounds = true,
            Tag = page
        };

        pageCanvas.Children.Add(CreatePageBackground(page, pageSize));

        // Images first so text controls stay above them for selection/editing.
        foreach (var image in page.ImageElements)
        {
            var bounds = GetDisplayBounds(page, image.Bounds, PointsToDips);
            if (bounds.Width <= 0 || bounds.Height <= 0) continue;

            pageCanvas.Children.Add(CreateImageElement(image, bounds));
        }

        foreach (var text in page.TextElements)
        {
            if (text.Bounds is not { } textBounds) continue;
            if (string.IsNullOrWhiteSpace(text.TextContent)) continue;

            var bounds = GetDisplayBounds(page, textBounds, PointsToDips);
            if (bounds.Width <= 0 || bounds.Height <= 0) continue;

            pageCanvas.Children.Add(CreateTextElement(
                text,
                bounds,
                NormalizeRotation(page.Rotation + text.Rotation)));
        }

        // Form layer is added last so it is always topmost and receives input first.
        if (fieldsByPage.TryGetValue(page.PageNumber, out FormFieldDescriptor[]? pageFields) &&
            pageFields.Length > 0)
        {
            IBrush formFieldBackground = CreateFormFieldBackground(
                pageCanvas.Background ?? Brushes.White);

            var formCanvas = new Canvas
            {
                Width = pageSize.Width,
                Height = pageSize.Height,
                Background = null,
                ClipToBounds = true
            };

            var formLayer = new ThemeVariantScope
            {
                RequestedThemeVariant = ThemeVariant.Light,
                Width = pageSize.Width,
                Height = pageSize.Height,
                ClipToBounds = true,
                Child = formCanvas
            };

            foreach (FormFieldDescriptor descriptor in pageFields)
                formCanvas.Children.Add(
                    CreateFormFieldElement(descriptor, formFieldBackground));

            pageCanvas.Children.Add(formLayer);
        }

        return pageCanvas;
    }

    private Control CreateFormFieldElement(
        FormFieldDescriptor descriptor,
        IBrush formFieldBackground)
    {
        double minSize = descriptor.Model switch
        {
            CheckBoxFieldModel => MinCheckBoxSizeDips,
            TextBoxFieldModel => MinTextBoxSizeDips,
            _ => 1.0
        };

        double hostWidth = Math.Max(descriptor.Bounds.Width, minSize);
        double hostHeight = Math.Max(descriptor.Bounds.Height, minSize);

        Control content;
        Action<bool>? setCheckboxVisual = null;

        switch (descriptor.Model)
        {
            case TextBoxFieldModel textBox:
                content = CreateTextBoxField(textBox, hostWidth, hostHeight);
                break;

            case CheckBoxFieldModel checkBox:
                (content, setCheckboxVisual) = CreateCheckboxVisual(checkBox, descriptor.Bounds);
                break;

            case ComboBoxFieldModel comboBox:
                content = CreateComboBoxField(comboBox);
                break;

            case ListBoxFieldModel listBox:
                content = CreateListBoxField(
                    listBox.Options,
                    listBox.SelectedIndices,
                    listBox.IsMultiselect,
                    indices => listBox.SelectedIndices = indices);
                break;

            case RadioButtonFieldModel radioButton:
                content = CreateRadioButtonField(radioButton);
                break;

            default:
                content = new Border();
                break;
        }

        if (setCheckboxVisual is null)
        {
            content.HorizontalAlignment = HorizontalAlignment.Stretch;
            content.VerticalAlignment = VerticalAlignment.Stretch;
        }

        content.Margin = new Thickness(0);
        content.MinWidth = 0;
        content.MinHeight = 0;

        bool allowFieldOverflow =
            descriptor.Model is CheckBoxFieldModel or TextBoxFieldModel;

        var host = new Border
        {
            Background = formFieldBackground,
            BorderThickness = new Thickness(0),
            Padding = new Thickness(0),
            Margin = new Thickness(0),
            ClipToBounds = !allowFieldOverflow,
            Child = content
        };

        // Keep the visual small and centered, but make the entire PDF field bounds clickable.
        if (setCheckboxVisual is not null &&
            descriptor.Model is CheckBoxFieldModel checkBoxModel)
        {
            host.Cursor = new Cursor(StandardCursorType.Hand);

            host.PointerPressed += (_, e) =>
            {
                if (!e.GetCurrentPoint(host).Properties.IsLeftButtonPressed)
                    return;

                checkBoxModel.IsChecked = !checkBoxModel.IsChecked;
                setCheckboxVisual(checkBoxModel.IsChecked);
                content.Focus();

                e.Handled = true;
            };
        }

        // Keep the enlarged field centered on the original PDF rectangle.
        Canvas.SetLeft(
            host,
            descriptor.Bounds.X + (descriptor.Bounds.Width - hostWidth) / 2.0);

        Canvas.SetTop(
            host,
            descriptor.Bounds.Y + (descriptor.Bounds.Height - hostHeight) / 2.0);

        host.Width = hostWidth;
        host.Height = hostHeight;

        FormFields[descriptor.WidgetKey] = host;

        return host;
    }

    private static TextBox CreateTextBoxField(
        TextBoxFieldModel model,
        double hostWidth,
        double hostHeight)
    {
        double padding = hostHeight < SmallTextBoxHeightThresholdDips
            ? SmallTextBoxPaddingDips
            : TextBoxPaddingDips;

        double fontSize = GetTextBoxFontSize(
            model,
            Math.Max(1.0, hostWidth - padding * 2.0),
            Math.Max(1.0, hostHeight - padding * 2.0));

        var textBox = new TextBox
        {
            Text = model.Value ?? string.Empty,
            FontSize = fontSize,
            FontFamily = ResolveFontFamily(model.FontName),
            AcceptsReturn = model.IsMultiline,
            TextWrapping = model.IsMultiline ? TextWrapping.Wrap : TextWrapping.NoWrap,
            Foreground = ToBrush(model.Color, Brushes.Black),
            Background = Brushes.Transparent,
            BorderThickness = new Thickness(0),
            Padding = new Thickness(padding),
            Margin = new Thickness(0),
            MinWidth = 0,
            MinHeight = 0,
            MaxLength = model.MaxLength ?? 0
        };

        if (model.IsScrollable)
            ScrollViewer.SetVerticalScrollBarVisibility(textBox, ScrollBarVisibility.Auto);

        textBox.TextChanged += (_, _) => model.Value = textBox.Text ?? string.Empty;

        return textBox;
    }

    private static (Control Visual, Action<bool> SetChecked) CreateCheckboxVisual(
        CheckBoxFieldModel model,
        Rect bounds)
    {
        double size = Math.Max(
            MinCheckBoxSizeDips,
            Math.Min(bounds.Width, bounds.Height) * CheckBoxScale);

        var glyph = new TextBlock
        {
            Text = model.IsChecked ? "✓" : string.Empty,
            Foreground = Brushes.Black,
            FontSize = Math.Max(8.0, size * 0.9),
            HorizontalAlignment = HorizontalAlignment.Center,
            VerticalAlignment = VerticalAlignment.Center,
            Margin = new Thickness(0),
            Padding = new Thickness(0)
        };

        var box = new Border
        {
            Width = size,
            Height = size,
            Background = Brushes.Transparent,
            BorderBrush = Brushes.Black,
            BorderThickness = new Thickness(1),
            CornerRadius = new CornerRadius(2),
            Child = glyph,
            Focusable = true,
            HorizontalAlignment = HorizontalAlignment.Center,
            VerticalAlignment = VerticalAlignment.Center,
            Margin = new Thickness(0),
            Padding = new Thickness(0)
        };

        void SetChecked(bool isChecked) =>
            glyph.Text = isChecked ? "✓" : string.Empty;

        box.KeyDown += (_, e) =>
        {
            if (e.Key != Key.Space)
                return;

            model.IsChecked = !model.IsChecked;
            SetChecked(model.IsChecked);
            e.Handled = true;
        };

        return (box, SetChecked);
    }

    private static ComboBox CreateComboBoxField(ComboBoxFieldModel model)
    {
        (string[] items, int[] optionIndices) = GetChoiceItems(model.Options);
        int[] displayIndices = GetDisplayIndices(model.SelectedIndices, optionIndices);

        var comboBox = new ComboBox
        {
            ItemsSource = items,
            Background = Brushes.Transparent,
            BorderThickness = new Thickness(0),
            Padding = new Thickness(0),
            Margin = new Thickness(0),
            MinWidth = 0,
            MinHeight = 0,
            HorizontalContentAlignment = HorizontalAlignment.Left,
            VerticalContentAlignment = VerticalAlignment.Center
        };

        if (displayIndices.Length > 0)
            comboBox.SelectedIndex = displayIndices[0];

        comboBox.SelectionChanged += (_, _) =>
            model.SelectedIndices = GetSelectedOptionIndices(
                comboBox.SelectedIndex >= 0 ? [comboBox.SelectedIndex] : [],
                optionIndices);

        return comboBox;
    }

    private static ListBox CreateListBoxField(
        string?[] options,
        int[] selectedIndices,
        bool isMultiselect,
        Action<int[]> writeBack)
    {
        (string[] items, int[] optionIndices) = GetChoiceItems(options);
        int[] displayIndices = GetDisplayIndices(selectedIndices, optionIndices);

        var listBox = new ListBox
        {
            ItemsSource = items,
            SelectionMode = isMultiselect ? SelectionMode.Multiple : SelectionMode.Single,
            Background = Brushes.Transparent,
            BorderThickness = new Thickness(0),
            Padding = new Thickness(0),
            Margin = new Thickness(0),
            MinWidth = 0,
            MinHeight = 0
        };

        foreach (int displayIndex in displayIndices)
        {
            if (displayIndex >= 0 && displayIndex < items.Length)
                listBox.Selection.Select(displayIndex);
        }

        listBox.SelectionChanged += (_, _) =>
            writeBack(GetSelectedOptionIndices(
                listBox.Selection.SelectedIndexes,
                optionIndices));

        return listBox;
    }

    private static Control CreateRadioButtonField(RadioButtonFieldModel model)
    {
        var panel = new StackPanel
        {
            Orientation = Orientation.Vertical,
            Spacing = 2,
            Margin = new Thickness(0),
            HorizontalAlignment = HorizontalAlignment.Stretch,
            VerticalAlignment = VerticalAlignment.Stretch
        };

        for (int i = 0; i < model.Options.Length; i++)
        {
            if (model.Options[i] is not string option) continue;
            int optionIndex = i;

            if (model.IsMultiselect)
            {
                var checkBox = new CheckBox
                {
                    Content = option,
                    IsChecked = model.SelectedIndices.Contains(optionIndex),
                    Background = Brushes.Transparent,
                    BorderThickness = new Thickness(0),
                    Padding = new Thickness(0),
                    Margin = new Thickness(0),
                    MinWidth = 0,
                    MinHeight = 0,
                    HorizontalAlignment = HorizontalAlignment.Stretch,
                    VerticalContentAlignment = VerticalAlignment.Center
                };

                checkBox.PropertyChanged += (_, e) =>
                {
                    if (e.Property == CheckBox.IsCheckedProperty)
                        SetSelectedIndex(model, optionIndex, checkBox.IsChecked ?? false);
                };

                panel.Children.Add(checkBox);
            }
            else
            {
                var radioButton = new RadioButton
                {
                    Content = option,
                    GroupName = model.FieldName,
                    IsChecked = model.SelectedIndices.Contains(optionIndex),
                    Background = Brushes.Transparent,
                    BorderThickness = new Thickness(0),
                    Padding = new Thickness(0),
                    Margin = new Thickness(0),
                    MinWidth = 0,
                    MinHeight = 0,
                    HorizontalAlignment = HorizontalAlignment.Stretch,
                    VerticalContentAlignment = VerticalAlignment.Center
                };

                radioButton.IsCheckedChanged += (_, _) => model.SelectedIndices = [optionIndex];

                panel.Children.Add(radioButton);
            }
        }

        return panel;
    }

    private static void SetSelectedIndex(RadioButtonFieldModel model, int index, bool isSelected)
    {
        List<int> indices = [.. model.SelectedIndices];

        if (isSelected)
        {
            if (!indices.Contains(index)) indices.Add(index);
        }
        else
        {
            indices.Remove(index);
        }

        indices.Sort();
        model.SelectedIndices = [.. indices];
    }

    // Maps a display item index back to the original (possibly null-containing) Options index.
    private static (string[] Items, int[] OptionIndices) GetChoiceItems(string?[] options)
    {
        List<string> items = [];
        List<int> optionIndices = [];

        for (int i = 0; i < options.Length; i++)
        {
            if (options[i] is string value)
            {
                items.Add(value);
                optionIndices.Add(i);
            }
        }

        return ([.. items], [.. optionIndices]);
    }

    private static int[] GetDisplayIndices(int[] selectedIndices, int[] optionIndices)
    {
        List<int> result = [];

        foreach (int originalIndex in selectedIndices)
        {
            int displayIndex = Array.IndexOf(optionIndices, originalIndex);
            if (displayIndex >= 0) result.Add(displayIndex);
        }

        return [.. result];
    }

    private static int[] GetSelectedOptionIndices(
        IEnumerable<int> displayIndices,
        int[] optionIndices)
    {
        List<int> result = [];

        foreach (int displayIndex in displayIndices)
        {
            if (displayIndex >= 0 && displayIndex < optionIndices.Length)
                result.Add(optionIndices[displayIndex]);
        }

        return [.. result];
    }

    private static Control CreatePageBackground(PdfPageModel page, Size pageSize)
    {
        if (page.BackgroundImage is not { Length: > 0 })
        {
            return new Border
            {
                Width = pageSize.Width,
                Height = pageSize.Height,
                Background = Brushes.White
            };
        }

        if (page.BackgroundImageType == PdfPageBackgroundImageType.Vector)
        {
            using var svgStream = new MemoryStream(page.BackgroundImage);
            var svgSource = SvgSource.LoadFromStream(svgStream);

            return new Image
            {
                Source = new SvgImage { Source = svgSource },
                Stretch = Stretch.Fill,
                Width = pageSize.Width,
                Height = pageSize.Height
            };
        }

        using var bitmapStream = new MemoryStream(page.BackgroundImage);

        return new Image
        {
            Source = new Bitmap(bitmapStream),
            Stretch = Stretch.Fill,
            Width = pageSize.Width,
            Height = pageSize.Height
        };
    }

    private static SelectableTextBlock CreateTextElement(
    PdfTextElementModel text,
    Rect bounds,
    double rotation)
    {
        double fontSize = Math.Max(text.FontSize ?? 12.0, 1.0) * PointsToDips;
        bool sideways = rotation is 90 or 270;

        // Use the PDF rectangle directly. Padding and fallback-font metric assumptions made the
        // overlay boxes oversized and shifted relative to the text baked into the page image.
        Size layoutSize = sideways
            ? new Size(bounds.Height, bounds.Width)
            : new Size(bounds.Width, bounds.Height);

        double left = bounds.X + (bounds.Width - layoutSize.Width) / 2.0;
        double top = bounds.Y + (bounds.Height - layoutSize.Height) / 2.0;

        // Text using custom embedded/subset fonts is already rendered by Aspose in the page
        // background. Keep a transparent text block so the text can still be selected and copied.
        bool renderedInBackground = text.RequiresRasterFont;

        var textBlock = new SelectableTextBlock
        {
            Text = text.TextContent,
            FontSize = fontSize,
            FontFamily = ResolveFontFamily(text.FontName),
            Foreground = renderedInBackground
                ? Brushes.Transparent
                : ToBrush(text.ForegroundColor, Brushes.Black),
            SelectionBrush = TextSelectionHighlightBrush,
            SelectionForegroundBrush = renderedInBackground
                ? Brushes.Transparent
                : ToBrush(text.ForegroundColor, Brushes.Black),
            Background = Brushes.Transparent,
            Padding = new Thickness(0),
            Margin = new Thickness(0),
            MinWidth = 0,
            MinHeight = 0,
            Width = layoutSize.Width,
            Height = layoutSize.Height,
            TextWrapping = TextWrapping.NoWrap,
            TextTrimming = TextTrimming.None,
            ClipToBounds = true
        };

        // PDF rotation is counterclockwise in PDF space; Avalonia's positive
        // RotateTransform is clockwise on screen, so negate it.
        if (rotation is not 0)
        {
            textBlock.RenderTransformOrigin = RelativePoint.Center;
            textBlock.RenderTransform = new RotateTransform(-rotation);
        }

        Canvas.SetLeft(textBlock, left);
        Canvas.SetTop(textBlock, top);

        return textBlock;
    }

    private static Control CreateImageElement(PdfImageElementModel image, Rect bounds)
    {
        // The image is already painted in the page background by Aspose's renderer.
        // Drawing it again would duplicate it, cover other content, and lose
        // clipping/alpha/CMYK handling. Use a transparent hit target instead.
        var hitArea = new Border
        {
            Background = Brushes.Transparent,
            Width = Math.Max(bounds.Width, 1.0),
            Height = Math.Max(bounds.Height, 1.0),
            Cursor = new Cursor(StandardCursorType.Hand)
        };

        Canvas.SetLeft(hitArea, bounds.X);
        Canvas.SetTop(hitArea, bounds.Y);

        return hitArea;
    }

    private static Size GetDisplaySize(PdfPageModel page, double scale)
    {
        var rotation = NormalizeRotation(page.Rotation);
        var sideways = rotation is 90 or 270;

        var width = sideways ? page.Dimensions.Height : page.Dimensions.Width;
        var height = sideways ? page.Dimensions.Width : page.Dimensions.Height;

        return new Size(Math.Max(width, 1.0) * scale, Math.Max(height, 1.0) * scale);
    }

    private static Rect GetDisplayBounds(PdfPageModel page, DrawingRectangle bounds, double scale)
    {
        var pageWidth = page.Dimensions.Width;
        var pageHeight = page.Dimensions.Height;

        // PDF origin is bottom-left with Y increasing upward.
        var x = bounds.X;
        var y = pageHeight - bounds.Y - bounds.Height;
        var width = bounds.Width;
        var height = bounds.Height;

        // The SVG device renders the page with its rotation applied, so map into
        // the displayed page space before scaling to DIPs.
        return NormalizeRotation(page.Rotation) switch
        {
            90 => new Rect((pageHeight - y - height) * scale, x * scale, height * scale, width * scale),
            180 => new Rect((pageWidth - x - width) * scale, (pageHeight - y - height) * scale, width * scale, height * scale),
            270 => new Rect(y * scale, (pageWidth - x - width) * scale, height * scale, width * scale),
            _ => new Rect(x * scale, y * scale, width * scale, height * scale)
        };
    }

    private static double NormalizeRotation(double rotation) => ((rotation % 360.0) + 360.0) % 360.0;

    private static IBrush CreateFormFieldBackground(IBrush pageBackground)
    {
        return pageBackground is SolidColorBrush solid
            ? new SolidColorBrush(Color.FromArgb(
                FormFieldBackgroundAlpha,
                solid.Color.R,
                solid.Color.G,
                solid.Color.B))
            : new SolidColorBrush(Color.FromArgb(
                FormFieldBackgroundAlpha,
                255,
                255,
                255));
    }

    private static double GetTextBoxFontSize(
    TextBoxFieldModel model,
    double availableWidth,
    double availableHeight)
    {
        double preferred = model.FontSize is double pdfFontSize && pdfFontSize > 0
            ? pdfFontSize * PointsToDips
            : MaxTextBoxFontSizeDips;

        double textLength = model.Value is { Length: > 0 } text
            ? Math.Max(1, text.Split('\n').Max(line => line.TrimEnd('\r').Length))
            : 1;

        double heightLimit = availableHeight / 1.25;
        double widthLimit = availableWidth / (0.62 * textLength);

        double allowedFontSize = Math.Min(
            preferred,
            Math.Min(heightLimit, widthLimit));

        return Math.Clamp(
            allowedFontSize,
            MinTextBoxFontSizeDips,
            MaxTextBoxFontSizeDips);
    }

    private static IBrush ToBrush(DrawingColor? color, IBrush fallback)
    {
        return color is { } value
            ? new SolidColorBrush(Color.FromArgb(value.A, value.R, value.G, value.B))
            : fallback;
    }

    // Changed by OpenCode's Big Pickle: resolves PDF/PostScript font names against installed
    // Avalonia font families. Custom embedded PDF subsets are not usable as UI fonts, so that text
    // stays visible in Aspose's rendered page image and this family only affects its transparent
    // selection overlay. Standard text remains visible here.
    private static FontFamily ResolveFontFamily(string? fontName)
    {
        if (string.IsNullOrWhiteSpace(fontName)) return FontFamily.Default;

        string name = StripPdfSubsetPrefix(fontName);

        foreach (string candidate in GetFontFamilyCandidates(name))
        {
            if (string.IsNullOrWhiteSpace(candidate)) continue;

            try
            {
                FontFamily family = new(candidate);
                if (FontManager.Current.TryGetGlyphTypeface(new Typeface(family), out _))
                    return family;
            }
            catch
            {
                // Try the next candidate.
            }
        }

        return FontFamily.Default;
    }

    // Generated by OpenCode's Big Pickle: strips PDF subset prefixes like "ABCDEF+TimesNewRomanPSMT".
    private static string StripPdfSubsetPrefix(string fontName)
    {
        int separator = fontName.IndexOf('+');
        return separator >= 0 && separator < fontName.Length - 1
            ? fontName[(separator + 1)..]
            : fontName;
    }

    // Changed by OpenCode's Big Pickle: normalizes punctuation and adds BattleTech font mappings.
    private static IEnumerable<string> GetFontFamilyCandidates(string fontName)
    {
        yield return fontName;

        // Changed by OpenCode's Big Pickle: allows "MyriadPro-Regular" and "MyriadPro Regular"
        // to match the same mapping.
        string key = new string(fontName.Where(char.IsLetterOrDigit).ToArray()).ToLowerInvariant();

        string[] mapped = key switch
        {
            "timesnewromanpsmt" or "timesnewromanpsmtregular" or "timesnewroman" or
            "timesnewromanpsitalicmt" or "timesnewromanitalic" =>
                ["Times New Roman"],

            "timesnewromanbold" or "timesnewromanpsmtbold" =>
                ["Times New Roman"],

            "arialmt" or "arial" or "arialregular" or "helvetica" or "helveticamt" =>
                ["Arial", "Helvetica"],

            "couriernewpsmt" or "couriernew" or "courier" or "couriermt" =>
                ["Courier New", "Courier"],

            "calibri" or "calibriregular" =>
                ["Calibri"],

            "verdana" or "verdanaregular" =>
                ["Verdana"],

            // Changed by OpenCode's Big Pickle: removed the duplicate "tahoma" pattern from the old map.
            "tahoma" or "tahomaregular" =>
                ["Tahoma"],

            "symbolmt" or "symbol" =>
                ["Symbol"],

            "zapfdingbats" or "zapfdingbatscpsmt" =>
                ["Wingdings", "Segoe UI Symbol"],

            // Generated by OpenCode's Big Pickle: BattleTech PDF fallback mappings.
            "myriadpro" or "myriadproregular" or "myriadproreg" =>
                ["Myriad Pro", "Arial"],

            "myriadprobold" or "myriadproboldsc750" =>
                ["Myriad Pro", "Arial"],

            "myriadproit" or "myriadproitalic" or "myriadprocond" or "myriadprocondensed" =>
                ["Myriad Pro", "Arial"],

            "eurostile" or "eurostileregular" or "eurostilelts" or "eurostileltstd" =>
                ["Eurostile", "Arial"],

            "eurostilebold" or "eurostileltsbold" or "eurostileltstdbold" =>
                ["Eurostile", "Arial"],

            "armadurasolid" or "armadurasolidsc750" or "armadurastencil" =>
                ["Armadura Solid", "Arial"],

            _ => []
        };

        foreach (string family in mapped)
            yield return family;

        // Generated by OpenCode's Big Pickle: turns names like "TimesNewRoman" into "Times New Roman".
        yield return SplitCamelCaseFontName(fontName);
    }

    // Generated by OpenCode's Big Pickle: inserts spaces between lower-to-upper case transitions.
    private static string SplitCamelCaseFontName(string fontName)
    {
        if (string.IsNullOrWhiteSpace(fontName)) return fontName;

        System.Text.StringBuilder builder = new(fontName.Length + 8);
        builder.Append(fontName[0]);

        for (int i = 1; i < fontName.Length; i++)
        {
            char previous = fontName[i - 1];
            char current = fontName[i];

            if (char.IsLower(previous) && char.IsUpper(current))
                builder.Append(' ');

            builder.Append(current);
        }

        return builder.ToString();
    }
