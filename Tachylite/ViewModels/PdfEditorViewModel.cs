using System;
using System.Collections.ObjectModel;
using System.IO;
using Avalonia;
using Avalonia.Controls;
using Avalonia.Input;
using Avalonia.Media;
using Avalonia.Media.Imaging;
using Avalonia.Svg.Skia;
using CommunityToolkit.Mvvm.ComponentModel;
using Tachylite.Core.Models;
using Tachylite.Core.Services;
using DrawingColor = System.Drawing.Color;
using DrawingRectangle = System.Drawing.Rectangle;

namespace Tachylite.ViewModels;

public partial class PdfEditorViewModel : ViewModelBase
{
    private readonly IFileSystemService _fileSystemService;
    private readonly IPdfService _pdfService;
    // PointsToDips was generated by OpenCode BigPickle
    private const double PointsToDips = 96.0 / 72.0;
    private readonly PdfPageBackgroundImageType _backgroundImageType;
    [ObservableProperty]
    public partial string FilePath { get; set; }
    public PdfDocumentModel Document { get; set; }
    public ObservableCollection<Canvas> PageElements { get; set; } = [];

    public PdfEditorViewModel(IFileSystemService fileSystemService, IPdfService pdfService, string filePath, PdfPageBackgroundImageType backgroundImageType)
    {
        _fileSystemService = fileSystemService;
        _pdfService = pdfService;
        FilePath = filePath;
        _backgroundImageType = backgroundImageType;

        PopulatePageElements();
    }

    // All functions beyond this line were generated by OpenCode BigPickle
    public void PopulatePageElements()
    {
        var document = Document ??= _pdfService.ConstructPdfDocumentModel(
            _fileSystemService.ReadPdfData(FilePath),
            Path.GetFileName(FilePath),
            _backgroundImageType);

        PageElements.Clear();

        foreach (var page in document.Pages)
        {
            var pageSize = GetDisplaySize(page, PointsToDips);

            var pageCanvas = new Canvas
            {
                Width = pageSize.Width,
                Height = pageSize.Height,
                Background = Brushes.White,
                ClipToBounds = true,
                Tag = page
            };

            pageCanvas.Children.Add(CreatePageBackground(page, pageSize));

            // Images first so text controls stay above them for selection/editing.
            foreach (var image in page.ImageElements)
            {
                if (image.ImageData is not { Length: > 0 }) continue;

                var bounds = GetDisplayBounds(page, image.Bounds, PointsToDips);
                if (bounds.Width <= 0 || bounds.Height <= 0) continue;

                pageCanvas.Children.Add(CreateImageElement(image, bounds));
            }

            foreach (var text in page.TextElements)
            {
                if (text.Bounds is not { } textBounds) continue;
                if (string.IsNullOrWhiteSpace(text.TextContent)) continue;

                var bounds = GetDisplayBounds(page, textBounds, PointsToDips);
                if (bounds.Width <= 0 || bounds.Height <= 0) continue;

                pageCanvas.Children.Add(CreateTextElement(text, bounds));
            }

            PageElements.Add(pageCanvas);
        }
    }

    private static Control CreatePageBackground(PdfPageModel page, Size pageSize)
    {
        if (page.BackgroundImage is not { Length: > 0 })
        {
            return new Border
            {
                Width = pageSize.Width,
                Height = pageSize.Height,
                Background = Brushes.White
            };
        }

        if (page.BackgroundImageType == PdfPageBackgroundImageType.Vector)
        {
            using var svgStream = new MemoryStream(page.BackgroundImage);
            var svgSource = SvgSource.LoadFromStream(svgStream);

            return new Image
            {
                Source = new SvgImage { Source = svgSource },
                Stretch = Stretch.Fill,
                Width = pageSize.Width,
                Height = pageSize.Height
            };
        }

        using var bitmapStream = new MemoryStream(page.BackgroundImage);

        return new Image
        {
            Source = new Bitmap(bitmapStream),
            Stretch = Stretch.Fill,
            Width = pageSize.Width,
            Height = pageSize.Height
        };
    }

    private static SelectableTextBlock CreateTextElement(PdfTextElementModel text, Rect bounds)
    {
        // Swap to SelectableTextBlock if you only want selection/copy and no editing.
        var textBox = new SelectableTextBlock
        {
            Text = text.TextContent,
            FontSize = Math.Max(text.FontSize ?? 12.0, 1.0) * PointsToDips,
            FontFamily = GetFontFamily(text.FontName),
            Foreground = ToBrush(text.ForegroundColor, Brushes.Black),
            Background = ToBrush(text.BackgroundColor, Brushes.Transparent),
            Padding = new Thickness(0),
            Margin = new Thickness(0),
            MinWidth = 0,
            MinHeight = 0,
            // Width = Math.Max(bounds.Width, 1.0),
            TextWrapping = TextWrapping.NoWrap,
        };

        Canvas.SetLeft(textBox, bounds.X);
        Canvas.SetTop(textBox, bounds.Y);

        return textBox;
    }

    private static Image CreateImageElement(PdfImageElementModel image, Rect bounds)
    {
        using var imageStream = new MemoryStream(image.ImageData!);

        var imageControl = new Image
        {
            Source = new Bitmap(imageStream),
            Stretch = Stretch.Fill,
            Width = Math.Max(bounds.Width, 1.0),
            Height = Math.Max(bounds.Height, 1.0),
            Cursor = new Cursor(StandardCursorType.Hand)
        };

        Canvas.SetLeft(imageControl, bounds.X);
        Canvas.SetTop(imageControl, bounds.Y);

        return imageControl;
    }

    private static Size GetDisplaySize(PdfPageModel page, double scale)
    {
        var rotation = NormalizeRotation(page.Rotation);
        var sideways = rotation is 90 or 270;

        var width = sideways ? page.Dimensions.Height : page.Dimensions.Width;
        var height = sideways ? page.Dimensions.Width : page.Dimensions.Height;

        return new Size(Math.Max(width, 1.0) * scale, Math.Max(height, 1.0) * scale);
    }

    private static Rect GetDisplayBounds(PdfPageModel page, DrawingRectangle bounds, double scale)
    {
        var pageWidth = page.Dimensions.Width;
        var pageHeight = page.Dimensions.Height;

        // PDF origin is bottom-left with Y increasing upward.
        var x = bounds.X;
        var y = pageHeight - bounds.Y - bounds.Height;
        var width = bounds.Width;
        var height = bounds.Height;

        // The SVG device renders the page with its rotation applied, so map into
        // the displayed page space before scaling to DIPs.
        return NormalizeRotation(page.Rotation) switch
        {
            90 => new Rect((pageHeight - y - height) * scale, x * scale, height * scale, width * scale),
            180 => new Rect((pageWidth - x - width) * scale, (pageHeight - y - height) * scale, width * scale, height * scale),
            270 => new Rect(y * scale, (pageWidth - x - width) * scale, height * scale, width * scale),
            _ => new Rect(x * scale, y * scale, width * scale, height * scale)
        };
    }

    private static int NormalizeRotation(int rotation) => ((rotation % 360) + 360) % 360;

    private static IBrush ToBrush(DrawingColor? color, IBrush fallback)
    {
        return color is { } value
            ? new SolidColorBrush(Color.FromArgb(value.A, value.R, value.G, value.B))
            : fallback;
    }

    private static FontFamily GetFontFamily(string? fontName)
    {
        if (string.IsNullOrWhiteSpace(fontName)) return FontFamily.Default;

        // Subset fonts are named like "ABCDEF+TimesNewRomanPSMT".
        var separator = fontName.IndexOf('+');
        if (separator >= 0 && separator < fontName.Length - 1)
        {
            fontName = fontName[(separator + 1)..];
        }

        try
        {
            return new FontFamily(fontName);
        }
        catch
        {
            return FontFamily.Default;
        }
    }
}
